import test,{after} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import os from 'node:os';import path from 'node:path';
import {matchesClass} from './classMatching';
const root=mkdtempSync(path.join(os.tmpdir(),'qs-natural-'));process.env.APP_DATA_ROOT=root;
const {createWorkspaceContext,runWithWorkspace}=await import('../../../context/workspaceContext');
const {assistantSearch:search,assistantRead:read}=await import('./index');
const {teachingBusinessContext}=await import('./teaching');
const {createClass,createStudent,listCommitteeRoles,createCommitteeRole}=await import('../../../repositories/rosterRepository');
const {saveScheduleItem}=await import('../../../repositories/scheduleRepository');
const {closeRosterDatabase}=await import('../../../database/rosterDatabase');
after(()=>{closeRosterDatabase();rmSync(root,{recursive:true,force:true});});
test('class candidates support natural aliases without confusing 1,10,110 or different grades',()=>{
 const c={name:'初一（10）班',grade:'七年级',term:'2026秋'};
 for(const q of ['十班','10班','初一10班','初一(10)班','初一（十）班','七年级十班',' 初一 （１０） 班 '])assert.equal(matchesClass(q,c),true,q);
 for(const q of ['一班','1班','110班','初二10班','今天有课的那个班','初一1班'])assert.equal(matchesClass(q,c),false,q);
 assert.equal(matchesClass('初一',{name:'10班',grade:'七年级',term:''}),true);
 assert.equal(matchesClass('初一10班',{name:'10班',grade:'七年级',term:''}),true);
});
test('native read primitives can resolve today schedule to actual committee with ambiguity and isolation',async()=>{
 const a=createWorkspaceContext('teacher-a','workspace-a','teacher'),b=createWorkspaceContext('teacher-b','workspace-b','teacher');
 await runWithWorkspace(a,async()=>{
  const c=createClass({name:'初一（10）班',grade:'七年级',term:'2026秋',headTeacher:'合成教师',status:'active'});
  createClass({name:'初二（10）班',grade:'八年级',term:'2026秋',headTeacher:'合成教师',status:'active'});
  createClass({name:'初一（1）班',grade:'七年级',term:'2026秋',headTeacher:'合成教师',status:'active'});
  const role=listCommitteeRoles().find(r=>r.name==='班长')!;assert.ok(role);
  for(let n=1;n<40;n++)createStudent({classId:c.id,name:'普通合成学生'+n,studentNo:String(n)});
  const leader=createStudent({classId:c.id,name:'合成班长',studentNo:'40',committeeRoleIds:[role.id]});
  const candidates=search({type:'class',query:'十班'});assert.equal(candidates.page?.total,2);
  assert.equal(search({type:'class',query:'初一10班'}).data.items[0].ref.id,c.id);
  saveScheduleItem({day:6,period:2,title:'语文',time:'09:00',type:'class',scope:'teacher',classId:c.id,className:c.name} as any);
  saveScheduleItem({day:5,period:2,title:'语文',time:'09:00',type:'class',scope:'teacher',classId:c.id,className:c.name} as any);
  const courses=search({type:'schedule',filters:{onDate:'2026-10-31',scope:'teacher'}});assert.equal(courses.page?.total,1);
  const result=await read({ref:{type:'class',id:courses.data.items[0].classId},section:'committee'});
  assert.equal(result.data.items[0].name,'合成班长');assert.equal(result.data.items[0].ref.id,leader.id);assert.equal(result.page?.total,1);
  assert.match(courses.data.metadata.interpretation,/不.*实际出勤|未核实/);
  assert.equal(search({type:'schedule',filters:{weekday:7}}).page?.total,0);
  assert.throws(()=>search({type:'schedule',filters:{onDate:'2026-10-31',weekday:6}}),/只能提供一个/);
  assert.throws(()=>search({type:'schedule',filters:{onDate:'2026-02-30'}}));
  assert.throws(()=>search({type:'schedule',filters:{weekday:8}}));
  assert.equal(teachingBusinessContext().total,3);
  const viceRole=createCommitteeRole('副班长');
  createStudent({classId:c.id,name:'合成副班长',studentNo:'41',committeeRoleIds:[viceRole.id]});
  const first=await read({ref:{type:'class',id:c.id},section:'committee',limit:1});
  const second=await read({ref:{type:'class',id:c.id},section:'committee',limit:1,offset:1});
  assert.equal(first.page?.total,2);assert.equal(first.page?.nextOffset,1);assert.equal(first.completeness,'partial');
  assert.deepEqual([first.data.items[0],second.data.items[0]].map(s=>s.committeeRoles[0].name).sort(),['副班长','班长'].sort());
  for(let n=0;n<49;n++)createClass({name:'候选'+n,grade:'七年级',term:'2026秋',headTeacher:'合成教师',status:'active'});
  const context=teachingBusinessContext();assert.equal(context.total,52);assert.equal(context.classes.length,50);assert.equal(context.complete,false);
  assert.equal(runWithWorkspace(b,()=>teachingBusinessContext()).total,0);
  await assert.rejects(runWithWorkspace(b,()=>read({ref:{type:'class',id:c.id},section:'committee'})),/找不到/);
 });
});
